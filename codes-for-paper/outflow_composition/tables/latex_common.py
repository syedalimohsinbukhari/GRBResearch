"""Shared LaTeX helpers for the Phase 6 table generators (``stage1_to_latex.py``, ``stage2_to_latex.py``).

Same conventions as ``photospheric_radius/csv_to_latex.py`` (copied, not imported, per the cross-folder-import rule in
CLAUDE.md): the paper's per-burst and per-model macros, decimals derived numerically from the smallest error in a column,
asymmetric ``value_{-lo}^{+hi}`` cells. Pure formatting: no dependency on ``grb_research`` or ``results.json``.
"""

from __future__ import annotations

import numpy as np

GRB_TEX_MACROS = {
    "GRB080916C": r"\grbzeroeightzeroninesixteenC",
    "GRB131014A": r"\grbthirteentenfourteenA",
    "GRB140206B": r"\grbfourteenzerotwozerosixB",
    "GRB231129C": r"\grbtwentythreeeleventwentynineC",
}

# BibTeX keys for the two methods, both in GRBResearchPaper/ref.bib (added 2026-10-25).
BIB_GAO = "GaoZhang2015"
BIB_ZHANG_PEER = "ZhangPeer2009"
BIB_PEER = "Peer2007"

# Significant figures to preserve on the smallest error in a column.
ERROR_SIG_FIGS = 2
MISSING = "--"


def format_grb_name(grb_name):
    """The paper's macro for a burst name."""
    return GRB_TEX_MACROS.get(grb_name, grb_name)


def format_model_name(model_name):
    """The paper's macro for a model name (SBPL_BB -> \\sbplbb)."""
    return "\\" + model_name.lower().replace("_", "")


def decimals_for(errors, sig=ERROR_SIG_FIGS, cap=6):
    """Decimal places such that the smallest error in a column keeps ``sig`` significant figures."""
    values = np.asarray(errors, dtype=float)
    values = values[np.isfinite(values) & (values > 0)]
    if values.size == 0:
        return 2
    return max(0, min(int(sig - 1 - np.floor(np.log10(values.min()))), cap))


def format_value(value, err_lower, err_upper, decimals):
    """``$value_{-lower}^{+upper}$`` with a fixed number of decimals."""
    return f"${value:.{decimals}f}_{{-{err_lower:.{decimals}f}}}^{{+{err_upper:.{decimals}f}}}$"


def red(text):
    """Red text, as the appendix tables flag a MARGINAL model."""
    return f"\\textcolor{{red}}{{{text}}}"


def exponent(value):
    """Integer power of ten of a power-of-ten value, for a column header."""
    return int(round(np.log10(value)))


def energy_si(kev):
    """siunitx quantity for an energy given in keV."""
    for scale, unit in ((1.0e6, r"\giga\electronvolt"), (1.0e3, r"\mega\electronvolt"), (1.0, r"\kilo\electronvolt")):
        if kev >= scale:
            return f"\\SI{{{kev / scale:g}}}{{{unit}}}"


def band_si(low_kev, high_kev):
    """``\\SI{10}{\\kilo\\electronvolt}--\\SI{10}{\\giga\\electronvolt}``."""
    return f"{energy_si(low_kev)}--{energy_si(high_kev)}"


def tablenotes(notes):
    """A ``tablenotes`` block from (marker, text) pairs, or an empty string when there are none."""
    if not notes:
        return ""
    body = "".join(f"\\item[{marker}] {text}\n" for marker, text in notes)
    return "\\begin{tablenotes}\n\\footnotesize\n" + body + "\\end{tablenotes}\n"


def wrap_table(*, header_comment, caption, label, colspec, head, rows, notes, star=False):
    """A complete ``table`` (or ``table*``) in the layout of the project's other generated tables."""
    env, width = ("table*", "\\textwidth") if star else ("table", "\\columnwidth")
    return (
        f"% AUTO-GENERATED by {header_comment}\n"
        "% Do not edit by hand — regenerate from the CSV instead.\n"
        f"\\begin{{{env}}}[!ht]\n"
        "\\centering\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{{label}}}\n"
        f"\\resizebox{{{width}}}{{!}}{{\n"
        "\\begin{threeparttable}\n"
        "\\renewcommand{\\arraystretch}{1.25}\n"
        f"\\begin{{tabular}}{{{colspec}}}\n"
        "\\toprule\n"
        f"{head}"
        "\\midrule\n"
        f"{rows}"
        "\\bottomrule\n"
        "\\end{tabular}\n"
        f"{tablenotes(notes)}"
        "\\end{threeparttable}\n"
        "}\n"
        f"\\end{{{env}}}\n"
    )
